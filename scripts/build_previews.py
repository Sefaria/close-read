def opening_text(slug):
    """The first plain-text panel of a sheet, its language, and the words its first highlight lights."""
    sheet = json.loads((ROOT / "data" / f"{slug}.json").read_text())
    lang = "en" if sheet.get("primaryLanguage") == "en" else "he"
    for sec in sheet["sections"]:
        pt = sec.get("primaryText")
        if not pt or pt.get("mode") in ("image", "comparison") or not pt.get(lang):
            continue
        lit = next((s["highlight"] for s in sec.get("steps", []) if s.get("highlight")), [])
        phrases = [pt.get("words", {}).get(g, {}).get(lang) for g in lit]
        return pt["ref"], pt[lang], lang, [p for p in phrases if p]
    return None, None, lang, []


def mark(text, phrases):
    out = esc(text)
    for p in sorted(phrases, key=len, reverse=True):
        out = out.replace(esc(p), f"<mark>{esc(p)}</mark>", 1)
    return out


