def card_html(e):
    ref, text, lang, lit = opening_text(e["slug"])
    he = f'<div class="he">{esc(e["title"]["he"])}</div>' if e["title"].get("he") else ""
    panel = (f'<div class="panel"><div class="ref">{esc(ref)}</div>'
             f'<p class="verse {lang}">{mark(text, lit)}</p></div>') if text else "<div></div>"
    return f"""<!doctype html><html><head><meta charset="utf-8">{FONTS}<style>{CARD_CSS}</style></head>
<body><div class="text"><div class="brand">{MARK_SVG}Close Read</div>{he}
<div class="en">{esc(e["title"]["en"])}</div><div class="author">{esc(e["author"]["en"])}</div>
{f'<div class="desc">{esc(e["description"])}</div>' if e.get("description") else ""}</div>{panel}</body></html>"""


def home_html():
    poster = "data:image/jpeg;base64," + base64.b64encode((ROOT / "assets" / "hero" / "bereshit-walkthrough.jpg").read_bytes()).decode()
    return f"""<!doctype html><html><head><meta charset="utf-8">{FONTS}<style>{CARD_CSS}</style></head>
<body class="home"><div class="text"><div class="brand">{MARK_SVG}Close Read</div>
<div class="en">The pull of video, at the learner’s pace.</div>
<div class="desc">A teacher’s sources and questions, as a guided, branching reading.</div></div>
<div class="shot"><img src="{poster}"></div></body></html>"""


def render_images(only=None):
    from playwright.sync_api import sync_playwright
    PREVIEWS.mkdir(parents=True, exist_ok=True)
    jobs = [("home", home_html())] + [(e["slug"], card_html(e)) for e in load_index()]
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page(viewport={"width": W, "height": H})
        for name, doc in jobs:
            if only and name not in only:
                continue
            page.set_content(doc, wait_until="networkidle")
            page.evaluate("document.fonts.ready")
            path = PREVIEWS / f"{name}.jpg"
            path.parent.mkdir(parents=True, exist_ok=True)
            page.screenshot(path=str(path), type="jpeg", quality=88)
            print(f"{path.relative_to(ROOT)}  {path.stat().st_size // 1024} KB")
        browser.close()


def main():
    for path, content in expected_pages().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text() != content:
            path.write_text(content)
            print(f"wrote {path.relative_to(ROOT)}")
    if "--images" in sys.argv:
        render_images([a for a in sys.argv[1:] if not a.startswith("--")] or None)


if __name__ == "__main__":
    main()
