ROOT = Path(__file__).resolve().parent.parent
SITE = "https://sefaria.github.io/close-read/"
PREVIEWS = ROOT / "assets" / "previews"
W, H = 1200, 630

HOME = {
    "title": "Close Read",
    "description": "Torah study with the pull of video, at the learner’s pace. A teacher’s sources and questions become a guided, branching reading.",
    "alt": "Close Read: the pull of video, at the learner’s pace. A page of the Leningrad Codex with the scribe’s breaks highlighted.",
}

START, END = "  <!-- share:start", "<!-- share:end -->"


def load_index():
    return [e for e in json.loads((ROOT / "data" / "index.json").read_text())
            if not e["slug"].startswith("examples/")]


def esc(s):
    return html.escape(s, quote=True)


def share_block(title, description, url, image, alt):
    tags = [
        f'<meta name="description" content="{esc(description)}">',
        '<meta property="og:type" content="website">',
        '<meta property="og:site_name" content="Close Read">',
        f'<meta property="og:title" content="{esc(title)}">',
        f'<meta property="og:description" content="{esc(description)}">',
        f'<meta property="og:url" content="{esc(url)}">',
        f'<meta property="og:image" content="{esc(image)}">',
        f'<meta property="og:image:width" content="{W}">',
        f'<meta property="og:image:height" content="{H}">',
        f'<meta property="og:image:alt" content="{esc(alt)}">',
        '<meta name="twitter:card" content="summary_large_image">',
        f'<meta name="twitter:title" content="{esc(title)}">',
        f'<meta name="twitter:description" content="{esc(description)}">',
        f'<meta name="twitter:image" content="{esc(image)}">',
    ]
    return ("  <!-- share:start (generated by scripts/build_previews.py) -->\n"
            + "".join(f"  {t}\n" for t in tags) + "  " + END)


def with_share(page, block):
    a, b = page.index(START), page.index(END) + len(END)
    return page[:a] + block + page[b:]


def sheet_title(e):
    return f"{e['title']['en']} · Close Read"


def sheet_description(e):
    by = e["author"]["en"]
    return f"{e['description']} A guided close reading, from {by}." if e.get("description") else f"A guided close reading, from {by}."


def render_index(template):
    return with_share(template, share_block(
        HOME["title"], HOME["description"], SITE, SITE + "assets/previews/home.jpg", HOME["alt"]))


def render_sheet_page(template, e):
    slug = e["slug"]
    page = with_share(template, share_block(
        sheet_title(e), sheet_description(e), f"{SITE}read/{slug}/",
        f"{SITE}assets/previews/{slug}.jpg",
        f"{e['title']['en']}, {e['author']['en']}: the opening text with its first words highlighted."))
    page = page.replace('<html lang="en">', f'<html lang="en" data-sheet="{esc(slug)}">', 1)
    page = page.replace("<head>\n", '<head>\n  <!-- Generated by scripts/build_previews.py from index.html. Do not edit. -->\n'
                        '  <base href="../../">\n', 1)
    page = re.sub(r"<title>.*?</title>", f"<title>{esc('Close Read: ' + e['title']['en'] + ' - ' + e['author']['en'])}</title>", page, count=1)
    return page


def expected_pages():
    """{path: content} for every generated page, plus the regenerated index.html."""
    template = (ROOT / "index.html").read_text()
    out = {ROOT / "index.html": render_index(template)}
    for e in load_index():
        out[ROOT / "read" / e["slug"] / "index.html"] = render_sheet_page(out[ROOT / "index.html"], e)
    return out


