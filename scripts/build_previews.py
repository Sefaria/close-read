"""Link previews: a share page and a preview image for the homepage and every reading.

Crawlers (Slack, iMessage, WhatsApp, social sites) read <meta> tags from the
HTML they fetch and don't run JavaScript, so a single index.html?sheet=... can
only ever show one preview. Each reading therefore gets its own page at
read/<slug>/index.html: a copy of index.html with <base href="../../"> (so CSS,
JS and data/ resolve from the site root), data-sheet="<slug>" on <html> (the
engine reads it when there's no ?sheet=), and its own Open Graph / Twitter tags.
?sheet= links keep working; read/<slug>/ is the form to share.

    python3 scripts/build_previews.py           # pages + tags only (fast, no browser)
    python3 scripts/build_previews.py --images  # also re-render assets/previews/*.jpg

Re-run after any change to index.html (including ?v= bumps) or data/index.json;
tests/test_data.py fails while the generated pages are stale. Re-render images
when a reading's title, description or opening verse changes.
"""

